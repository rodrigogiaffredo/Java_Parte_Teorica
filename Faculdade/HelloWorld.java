

/**
 * Hello, World! Proposto no tutorial de validação da instalação do Java no VS Code.
 * Linha 1: public class HelloWorld {
 * Essa linha cria uma classe chamada HelloWorld.
 * Uma classe é uma “caixa” que organiza o seu código.
 * Neste começo, você pode pensar que a classe é o “nome do programa”.

 * Linha 2: public static void main(String[] args) {
 * Essa linha cria o método main, que é o ponto de entrada do programa.
 * Isso significa que o Java começa a executar o seu programa a partir daqui.
 * A palavra public indica que esse método pode ser acessado de fora.
 * A palavra static permite que o Java execute esse método sem precisar criar um objeto da classe.
 * A palavra void indica que o método não devolve um valor de retorno.
 * O trecho String[] args representa argumentos que poderiam ser passados pela linha de comando, e você vai ver isso mais adiante no curso.

 * Linha 3: System.out.println("Hello, World!");
 * Essa linha imprime um texto no console.
 * System.out representa a saída padrão (o console).
 * println imprime e pula uma linha no final.
 * As aspas indicam que "Hello, World!" é um texto (uma string).

 * Linhas 4 e 5: }
 * Essas chaves fecham o método main e depois fecham a classe.
 * Uma regra prática é: cada { precisa ter um } correspondente.
 */

public class HelloWorld {
    
    public static void main(String[] args) {
        System.out.println("Hello, World!");
    }
}